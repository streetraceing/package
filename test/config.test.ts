test('configuration validates package hooks and apply cleanup settings', async () => {
  const workspace = await mkdtemp(path.join(tmpdir(), 'package-hooks-config-'));
  try {
    await writeFile(
      path.join(workspace, '.packagerc'),
      JSON.stringify(
        {
          beforePackage: 'npm run build',
          afterPackage: ['node scripts/report.mjs'],
          beforeApply: 'npm run migrate',
          afterApply: ['npm run prepare'],
          packageManager: 'pnpm',
          packageManagerIgnore: true,
          packageManagerIgnoreFile: '.publishignore',
          deletePackageOnApply: true,
          deleteSourcePackageOnApply: true,
          saveDeletedCache: false,
        },
        null,
        2,
      ),
      'utf8',
    );
    const loaded = await loadConfig(workspace);
    assert.deepEqual(loaded.config.beforePackage, ['npm run build']);
    assert.deepEqual(loaded.config.afterPackage, ['node scripts/report.mjs']);
    assert.deepEqual(loaded.config.beforeApply, ['npm run migrate']);
    assert.deepEqual(loaded.config.afterApply, ['npm run prepare']);
    assert.equal(loaded.config.packageManager, 'pnpm');
    assert.equal(loaded.config.packageManagerIgnore, true);
    assert.equal(loaded.config.packageManagerIgnoreFile, '.publishignore');
    assert.equal(loaded.config.deletePackageOnApply, true);
    assert.equal(loaded.config.deleteSourcePackageOnApply, true);
    assert.equal(loaded.config.saveDeletedCache, false);

    await writeFile(
      path.join(workspace, '.packagerc'),
      '{"beforePackage":42}\n',
      'utf8',
    );
    await assert.rejects(
      loadConfig(workspace),
      /beforePackage must be a non-empty string or an array of non-empty strings/,
    );
  } finally {
    await rm(workspace, { recursive: true, force: true });
  }
});

test('configuration instances do not share mutable default arrays', async () => {
  const first = await loadConfig(process.cwd());
  const second = await loadConfig(process.cwd());
  first.config.ignore.push('temporary/**');
  first.config.monorepo.shared.push('custom.json');
  assert.deepEqual(second.config.ignore, []);
  assert.equal(second.config.monorepo.shared.includes('custom.json'), false);
});

test('explicit config paths resolve root relative to the config file', async () => {
  const workspace = await mkdtemp(path.join(tmpdir(), 'package-config-base-'));
  try {
    await writeFile(
      path.join(workspace, 'project.packagerc'),
      '{"root":"./source","output":"../artifacts"}\n',
      'utf8',
    );
    const loaded = await loadConfig(
      path.join(workspace, 'unrelated'),
      '../project.packagerc',
    );
    const { resolveConfigPaths } = await import('../src/config.js');
    const resolved = resolveConfigPaths(loaded.config, loaded.configDirectory);
    assert.equal(resolved.root, path.join(workspace, 'source'));
    assert.equal(resolved.output, path.join(workspace, 'artifacts'));
  } finally {
    await rm(workspace, { recursive: true, force: true });
  }
});

test('CLI value options require exact option names', () => {
  assert.throws(
    () => parseArgs(['zip', '--cwdish', 'somewhere']),
    /Unknown option: --cwdish/,
  );
  assert.throws(
    () => parseArgs(['zip', '--compression-level=12']),
    /integer from 0 to 9/,
  );
  assert.throws(
    () => parseArgs(['zip', '--cwd', '--quiet']),
    /--cwd requires a value/,
  );
  assert.equal(parseArgs(['zip', '-o=release.zip']).output, 'release.zip');
});

