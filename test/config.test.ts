test('package init updates .gitignore without duplicating its generated block', async () => {
  const workspace = await mkdtemp(path.join(tmpdir(), 'package-init-ignore-'));
  try {
    await writeFile(
      path.join(workspace, '.gitignore'),
      'node_modules/\n*.zip\n',
      'utf8',
    );
    await initCommand(workspace, false, false);
    await initCommand(workspace, true, false);

    const gitignore = await readFile(
      path.join(workspace, '.gitignore'),
      'utf8',
    );
    assert.equal(
      gitignore,
      'node_modules/\n# Generated by @streetraceing/package\n*.zip\n',
    );
    assert.equal(
      gitignore.match(/# Generated by @streetraceing\/package/g)?.length,
      1,
    );
    assert.equal(gitignore.match(/^\*\.zip$/gm)?.length, 1);
  } finally {
    await rm(workspace, { recursive: true, force: true });
  }
});

test('published JSON Schema matches configuration defaults', async () => {
  const schema = JSON.parse(
    await readFile(path.resolve('schema.json'), 'utf8'),
  ) as JsonSchema;
  assert.equal(schema.$id, configSchemaUrl);

  const properties = schema.properties ?? {};
  for (const [key, value] of Object.entries(defaultConfig)) {
    assert.deepEqual(
      properties[key]?.default,
      value,
      `schema default for ${key}`,
    );
  }
  assert.equal(properties.$schema?.default, configSchemaUrl);
  for (const [key, property] of Object.entries(properties)) {
    assert.ok(
      property.markdownDescription?.includes('`'),
      `schema markdownDescription for ${key}`,
    );
  }
});

